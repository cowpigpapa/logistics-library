-- 용어 검수표(/term-review): 운영자가 바뀐 용어를 판정하고 Claude가 읽어 반영한다. 관리자 키(link_check_secret)로만 읽고 쓴다.
create table if not exists public.term_review (
  id text primary key,
  grp text not null,
  frm text not null,
  dst text not null default '',
  count integer not null default 0,
  cats text not null default '',
  ex_from text not null default '',
  ex_to text not null default '',
  note text not null default '',
  verdict text not null default '' check (verdict in ('', 'keep', 'revert', 'other')),
  alt text not null default '',
  memo text not null default '',
  updated_at timestamptz
);
alter table public.term_review enable row level security;
revoke all on public.term_review from anon, authenticated;

create or replace function public.get_term_review(p_secret text)
returns setof public.term_review language plpgsql stable security definer set search_path = public, extensions, pg_temp
as $$
begin
  if not public.link_check_secret_ok(p_secret) then raise exception 'not allowed'; end if;
  return query select * from public.term_review order by id;
end;
$$;

create or replace function public.save_term_review(p_secret text, p_id text, p_verdict text, p_alt text, p_memo text)
returns timestamptz language plpgsql security definer set search_path = public, extensions, pg_temp
as $$
declare t timestamptz := now();
begin
  if not public.link_check_secret_ok(p_secret) then raise exception 'not allowed'; end if;
  update public.term_review set verdict = coalesce(p_verdict, ''), alt = left(coalesce(p_alt, ''), 300),
         memo = left(coalesce(p_memo, ''), 1000), updated_at = t where id = p_id;
  if not found then raise exception 'unknown id'; end if;
  return t;
end;
$$;
revoke all on function public.get_term_review(text) from public;
revoke all on function public.save_term_review(text, text, text, text, text) from public;
grant execute on function public.get_term_review(text) to anon;
grant execute on function public.save_term_review(text, text, text, text, text) to anon;

